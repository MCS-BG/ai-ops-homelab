MCP_PIN = "mcp==2.2.0"
SERVER_DEPS = [MCP_PIN, "psycopg[binary]==3.3.6", "requests==2.34.2"]


def block(path):
    text = (HERE / path).read_text()
    return "\n".join(("    " + line) if line else "" for line in text.rstrip("\n").split("\n"))


def pip_cmd(deps):
    args = ["python", "-m", "pip", "install", "--no-cache-dir", "--disable-pip-version-check",
            "--only-binary=:all:", "--quiet", "--target", "/deps"] + deps
    return "[" + ", ".join('"' + a + '"' for a in args) + "]"


